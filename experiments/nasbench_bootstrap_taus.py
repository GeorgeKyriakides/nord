# Useful constants
INPUT = 'input'
OUTPUT = 'output'
CONV3X3 = 'conv3x3-bn-relu'
CONV1X1 = 'conv1x1-bn-relu'
MAXPOOL3X3 = 'maxpool3x3'
NUM_VERTICES = 7
MAX_EDGES = 9
EDGE_SPOTS = NUM_VERTICES * (NUM_VERTICES - 1) / 2   # Upper triangular matrix
OP_SPOTS = NUM_VERTICES - 2   # Input/output vertices are fixed
ALLOWED_OPS = [CONV3X3, CONV1X1, MAXPOOL3X3]
ALLOWED_EDGES = [0, 1]   # Binary adjacency matrix

"""## Example search experiment (random vs. evolution)"""


def random_spec():
    """Returns a random valid spec."""
    while True:
        matrix = np.random.choice(
            ALLOWED_EDGES, size=(NUM_VERTICES, NUM_VERTICES))
        matrix = np.triu(matrix, 1)
        ops = np.random.choice(ALLOWED_OPS, size=(NUM_VERTICES)).tolist()
        ops[0] = INPUT
        ops[-1] = OUTPUT
        spec = api.ModelSpec(matrix=matrix, ops=ops)
        if nasbench.is_valid(spec):
            return spec


def sample_architectures(architectures=1000):

    nasbench.reset_budget_counters()
    times, full_valids, full_tests = [], [], []
    epochs = [4, 12, 36, 108]
    partial_valids, partial_tests = {e: []
                                     for e in epochs}, {e: [] for e in epochs}

    specs = []
    for _ in range(architectures):
        spec = random_spec()

        full_data = nasbench.query(spec)
        specs.append(spec)

        full_valids.append(full_data['validation_accuracy'])
        full_tests.append(full_data['test_accuracy'])

        for e in epochs:
            data = nasbench.query(spec, epochs=e)
            partial_valids[e].append(data['validation_accuracy'])
            partial_tests[e].append(data['test_accuracy'])

        time_spent, _ = nasbench.get_budget_counters()
        times.append(time_spent)

    return specs, times, partial_valids, partial_tests, full_valids, full_tests


