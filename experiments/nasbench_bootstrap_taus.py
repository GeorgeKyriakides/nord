def bootstrap_taus(fulls, partials):
    corrs = []
    partials_array = np.array(partials)
    fulls_array = np.array(fulls)
    for _ in range(800):
        inds = np.random.choice(
            [x for x in range(len(partials))], len(partials))

        partial_tests = partials_array[inds]
        full_tests = fulls_array[inds]

        partial_ranks = rankdata(partial_tests)
        full_ranks = rankdata(full_tests)

        corrs.append(kendalltau(partial_ranks, full_ranks)[0])

    return corrs


